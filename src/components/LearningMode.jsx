export default function LearningMode({
  onSelectPart = () => {},
  onExit = () => {},
  selectedPart = "",
}) {
  const [lessonIndex, setLessonIndex] = useState(0);
  const [completed, setCompleted] = useState([]);

  const lesson = lessons[lessonIndex];
  const progress = (completed.length / lessons.length) * 100;

  const selectLesson = (index) => {
    setLessonIndex(index);
    onSelectPart(lessons[index].name);
  };

  const markComplete = () => {
    setCompleted((previous) =>
      previous.includes(lesson.name)
        ? previous
        : [...previous, lesson.name]
    );
  };

  const resetProgress = () => {
    setCompleted([]);
    setLessonIndex(0);
    onSelectPart(lessons[0].name);
  };

  return (
    <main className="learning-page">
      <header className="learning-header">
        <div className="learning-brand">
          <div className="learning-brand-icon">
            <Cog size={22} />
          </div>
          <div>
            <h1>HORIZON</h1>
            <span>ENGINE LEARNING LAB</span>
          </div>
        </div>

        <div className="learning-header-right">
          <span className="learning-mode-label">
            <BookOpen size={15} />
            LEARNING MODE
          </span>
          <button
            className="learning-exit"
            onClick={onExit}
            aria-label="Exit learning mode"
          >
            <X size={19} />
          </button>
        </div>
      </header>

      <section className="learning-welcome">
        <div>
          <span className="learning-eyebrow">INTERACTIVE COURSE / 01</span>
          <h2>Understand the Engine.</h2>
          <p>
            Explore the components of an internal combustion engine,
            understand their functions, and discover how they work together.
          </p>
        </div>

        <div className="learning-progress-card">
          <div className="progress-heading">
            <span>YOUR PROGRESS</span>
            <strong>{completed.length}/{lessons.length}</strong>
          </div>
          <div className="progress-track">
            <div
              className="progress-fill"
              style={{ width: `${progress}%` }}
            />
          </div>
          <span className="progress-caption">
            {Math.round(progress)}% completed
          </span>
        </div>
      </section>

      <div className="learning-layout">
        <aside className="lesson-sidebar">
          <div className="sidebar-heading">
            <Layers3 size={17} />
            <span>ENGINE COMPONENTS</span>
          </div>

          <div className="lesson-list">
            {lessons.map((item, index) => (
              <button
                key={item.name}
                className={`lesson-item ${
                  index === lessonIndex ? "active" : ""
                }`}
                onClick={() => selectLesson(index)}
              >
                <span className="lesson-number">
                  {completed.includes(item.name) ? (
                    <CheckCircle2 size={17} />
                  ) : (
                    String(index + 1).padStart(2, "0")
                  )}
                </span>
                <span className="lesson-item-text">
                  <strong>{item.name}</strong>
                  <small>{item.category}</small>
                </span>
                {index === lessonIndex && (
                  <CircleDot size={15} className="lesson-active-icon" />
                )}
              </button>
            ))}
          </div>

          <button className="reset-progress" onClick={resetProgress}>
            <RotateCcw size={15} />
            Reset learning progress
          </button>
        </aside>

        <section className="lesson-content">
          <div className="lesson-topline">
            <span>LESSON {String(lessonIndex + 1).padStart(2, "0")}</span>
            <span>{lesson.category.toUpperCase()}</span>
          </div>

          <div className="lesson-title">
            <div>
              <span className="lesson-type">{lesson.type}</span>
              <h2>{lesson.name}</h2>
            </div>
            {completed.includes(lesson.name) && (
              <span className="completed-tag">
                <CheckCircle2 size={15} /> COMPLETED
              </span>
            )}
          </div>

          <div className="learning-engine-prompt">
            <div className="engine-prompt-icon">
              <Cog size={25} />
            </div>
            <div>
              <strong>Explore in the 3D engine</strong>
              <p>
                Select this component to highlight it in the engine viewport.
              </p>
            </div>
            <button
              onClick={() => onSelectPart(lesson.name)}
              className="explore-component"
            >
              <Play size={14} fill="currentColor" />
              Explore
            </button>
          </div>

          <div className="lesson-section">
            <span className="section-label">01 / OVERVIEW</span>
            <p>{lesson.description}</p>
          </div>

          <div className="lesson-info-grid">
            <article className="lesson-info-card">
              <span className="section-label">02 / FUNCTION</span>
              <h3>What does it do?</h3>
              <p>{lesson.function}</p>
            </article>

            <article className="lesson-info-card">
              <span className="section-label">03 / WORKING</span>
              <h3>How does it work?</h3>
              <p>{lesson.working}</p>
            </article>
          </div>

          <div className="lesson-section importance-section">
            <span className="section-label">04 / IMPORTANCE</span>
            <p>{lesson.importance}</p>
          </div>

          <div className="learning-fact">
            <span>ENGINE FACT</span>
            <p>{lesson.fact}</p>
          </div>

          <footer className="lesson-navigation">
            <button
              className="lesson-nav-button previous"
              disabled={lessonIndex === 0}
              onClick={() => selectLesson(lessonIndex - 1)}
            >
              <ArrowLeft size={17} />
              Previous
            </button>

            <button
              className="mark-complete"
              onClick={markComplete}
              disabled={completed.includes(lesson.name)}
            >
              <CheckCircle2 size={17} />
              {completed.includes(lesson.name)
                ? "Completed"
                : "Mark complete"}
            </button>

            <button
              className="lesson-nav-button next"
              disabled={lessonIndex === lessons.length - 1}
              onClick={() => selectLesson(lessonIndex + 1)}
            >
              Next
              <ArrowRight size={17} />
            </button>
          </footer>
        </section>
      </div>
    </main>
  );
}
